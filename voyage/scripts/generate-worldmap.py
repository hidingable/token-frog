#!/usr/bin/env python3
"""Rasterize world-atlas land-110m TopoJSON into Sources/VoyageCore/WorldMapData.swift.

Usage: generate-worldmap.py <land-110m.json> <output.swift>
"""
import json
import sys

WIDTH, HEIGHT = 120, 50
LAT_TOP, LAT_BOTTOM = 84.0, -60.0


def decode_arcs(topo):
    scale, translate = topo["transform"]["scale"], topo["transform"]["translate"]
    decoded = []
    for arc in topo["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * scale[0] + translate[0], y * scale[1] + translate[1]))
        decoded.append(points)
    return decoded


def ring_points(ring, arcs):
    points = []
    for index in ring:
        arc = arcs[index] if index >= 0 else list(reversed(arcs[~index]))
        points.extend(arc[1:] if points else arc)
    return points


def land_rings(topo):
    arcs = decode_arcs(topo)
    rings = []

    def add(geometry):
        kind = geometry["type"]
        if kind == "GeometryCollection":
            for child in geometry["geometries"]:
                add(child)
        elif kind == "Polygon":
            rings.extend(ring_points(ring, arcs) for ring in geometry["arcs"])
        elif kind == "MultiPolygon":
            for polygon in geometry["arcs"]:
                rings.extend(ring_points(ring, arcs) for ring in polygon)

    add(topo["objects"]["land"])
    return rings


def unwrap(ring):
    """Makes longitudes continuous so rings crossing the antimeridian do not smear across the map."""
    points = [ring[0]]
    for lon, lat in ring[1:]:
        while lon - points[-1][0] > 180:
            lon -= 360
        while lon - points[-1][0] < -180:
            lon += 360
        points.append((lon, lat))
    return points


def in_ring(lon, lat, ring):
    hit = False
    previous = ring[-1]
    for point in ring:
        if (point[1] > lat) != (previous[1] > lat):
            crossing = previous[0] + (lat - previous[1]) * (point[0] - previous[0]) / (point[1] - previous[1])
            if lon < crossing:
                hit = not hit
        previous = point
    return hit


def inside(lon, lat, rings):
    hit = False
    for ring in rings:
        if any(in_ring(lon + offset, lat, ring) for offset in (-360, 0, 360)):
            hit = not hit
    return hit


def main():
    source, output = sys.argv[1], sys.argv[2]
    with open(source, encoding="utf-8") as handle:
        rings = [unwrap(ring) for ring in land_rings(json.load(handle))]
    samples = [(0.5, 0.5), (0.2, 0.2), (0.8, 0.2), (0.2, 0.8), (0.8, 0.8)]
    rows = []
    for y in range(HEIGHT):
        row = ""
        for x in range(WIDTH):
            hits = 0
            for sx, sy in samples:
                lon = (x + sx) / WIDTH * 360 - 180
                lat = LAT_TOP - (y + sy) / HEIGHT * (LAT_TOP - LAT_BOTTOM)
                hits += inside(lon, lat, rings)
            row += "#" if hits >= 2 else "."
        rows.append(row)
    body = ",\n".join(f'        "{row}"' for row in rows)
    swift = f"""// Generated by scripts/generate-worldmap.py from world-atlas land-110m (Natural Earth, public domain).
public enum WorldMapData {{
    public static let width = {WIDTH}
    public static let height = {HEIGHT}
    public static let latTop = {LAT_TOP}
    public static let latBottom = {LAT_BOTTOM}
    public static let rows: [String] = [
{body},
    ]
}}
"""
    with open(output, "w", encoding="utf-8") as handle:
        handle.write(swift)
    print("\n".join(rows))


if __name__ == "__main__":
    main()
